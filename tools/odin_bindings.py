#!/usr/bin/env python3
"""Generate/check the deliberately raw ABI binding against the authoritative C header."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
HANDLES = {'wdb_database': 'Database', 'wdb_value': 'Value', 'wdb_snapshot': 'Snapshot',
           'wdb_tx': 'Transaction', 'wdb_scan': 'Scan'}

def generate(header):
    text = re.sub(r'/\*.*?\*/', '', header, flags=re.S)
    constants = re.findall(r'\b(WDB_\w+)\s*=\s*(\d+)', text)
    constants += re.findall(r'#define\s+(WDB_\w+)\s+(\d+)u', text)
    lines = ['// Generated by tools/odin_bindings.py. Do not edit declarations by hand.',
             '// Ownership, synchronization, buffer, and native-path rules: packaged weekend_db.h.',
             'package weekend_db', 'import "core:c"', '',
             'WEEKEND_DB_LIBRARY :: #config(WEEKEND_DB_LIBRARY, "weekend_db")',
             'foreign import engine { WEEKEND_DB_LIBRARY }', '', 'Status :: i32']
    lines += [f'{name} :: distinct rawptr' for name in HANDLES.values()]
    lines += ['#assert(size_of(Database) == size_of(rawptr))',
              '#assert(size_of(c.size_t) == size_of(uintptr))', '']
    lines += [f'{name} :: {value}' for name, value in constants]
    lines += ['', 'foreign engine {']
    declarations = re.findall(r'\b(wdb_status|uint32_t)\s+(wdb_\w+)\((.*?)\);', text, re.S)
    if set(re.findall(r'\b(wdb_\w+)\s*\(', text)) != {name for _, name, _ in declarations}:
        raise ValueError('Unsupported C function return/signature')
    if not declarations:
        raise ValueError('No C ABI declarations found')
    for result, name, arguments in declarations:
        params = []
        for argument in ([] if arguments.strip() == 'void' else arguments.split(',')):
            match = re.fullmatch(r'\s*(?:const\s+)?(\w+)\s*(\*\*|\*)?\s*(\w+)\s*', argument)
            if match is None:
                raise ValueError('Unsupported C declaration: ' + argument)
            base, pointer, parameter = match.groups()
            if base in HANDLES:
                kind = HANDLES[base]
                if pointer == '**':
                    kind = '^' + kind
                elif pointer != '*':
                    raise ValueError('Opaque handle must be a pointer')
            else:
                kind = {'uint8_t': 'u8', 'uint64_t': 'u64', 'int32_t': 'i32', 'size_t': 'c.size_t'}[base]
                if pointer:
                    if pointer != '*':
                        raise ValueError('Unexpected pointer depth')
                    kind = ('[^]' if base == 'uint8_t' or parameter == 'buffer' else '^') + kind
            if parameter == 'map':
                parameter = 'map_value'
            params.append(parameter + ': ' + kind)
        result = 'Status' if result == 'wdb_status' else 'u32'
        lines.append(f'    {name} :: proc({", ".join(params)}) -> {result} ---')
    lines += ['}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate((ROOT / 'include/weekend_db.h').read_text())
    path = ROOT / 'bindings/odin/weekend_db.odin'
    if args.check:
        if path.read_text() != result:
            raise SystemExit('Odin binding differs from C ABI; regenerate with tools/odin_bindings.py')
    else:
        path.write_text(result)

if __name__ == '__main__':
    main()
