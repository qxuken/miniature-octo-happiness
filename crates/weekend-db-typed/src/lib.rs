#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Error {
    Engine(engine::Error),
    Schema(schema::Error),
    InvalidField { id: u64, reason: &'static str },
    InvalidCatalog,
    NotInitialized,
    TypeMismatch,
    NotIndexed(u64),
    IndexLayoutChanged,
    UniqueViolation(u64),
    IndexInconsistent,
    MigrationRequired,
    UnsupportedVersion,
    InvalidId,
}
pub type Result<T> = std::result::Result<T, Error>;
impl From<engine::Error> for Error {
    fn from(e: engine::Error) -> Self {
        Self::Engine(e)
    }
}
impl From<schema::Error> for Error {
    fn from(e: schema::Error) -> Self {
        match e {
            schema::Error::Engine(e) => Self::Engine(e),
            other => Self::Schema(other),
        }
    }
}
impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Engine(error) => write!(f, "{error}"),
            Self::Schema(error) => write!(f, "{error}"),
            Self::UniqueViolation(id) => write!(f, "Unique field {id} is already in use"),
            Self::InvalidField { id, reason } => write!(f, "Invalid field {id}: {reason}"),
            Self::MigrationRequired => f.write_str("Older records require an explicit migration"),
            other => write!(f, "{other:?}"),
        }
    }
}
impl std::error::Error for Error {}

/// Generated by `#[derive(Model)]`. Stable IDs are explicit, independent of names.
pub trait Model: Sized {
    const TYPE_ID: u64;
    const VERSION: u64;
    const UNIQUE_FIELDS: &'static [u64];
    fn schema(db: &Database) -> Result<Schema>;
    fn decode(record: &Record, schema: &Schema) -> Result<Self>;
    fn patch(&self, db: &Database, record: &Record) -> Result<Record>;
}

// Public because expansions execute in the caller's crate, not this crate.
#[doc(hidden)]
pub mod __private {
    pub use crate::engine::{
        Database, Value,
        schema::{FieldSpec, Record, Schema},
    };
    pub use crate::{Error, FieldValue, Index, Model, Result, UniqueValue};

    fn decode_error(id: u64, error: crate::DecodeError) -> Error {
        match error {
            crate::DecodeError::Invalid(reason) => Error::InvalidField { id, reason },
            crate::DecodeError::OutOfMemory => Error::Engine(crate::engine::Error::OutOfMemory),
        }
    }
    pub fn read<T: FieldValue>(
        record: &Record,
        schema: &Schema,
        id: u64,
        version: u64,
        default: Option<fn() -> T>,
    ) -> Result<T> {
        if schema.field(id)?.is_none() {
            if schema.version() >= version {
                return Err(Error::UnsupportedVersion);
            }
            if record.field(id)?.is_some() {
                return Err(Error::Schema(
                    crate::engine::schema::Error::MigrationCollision,
                ));
            }
            if T::PRESERVE_MISSING {
                return T::missing().map_err(|error| decode_error(id, error));
            }
            return default.map_or_else(
                || T::missing().map_err(|error| decode_error(id, error)),
                |f| Ok(f()),
            );
        }
        let field = schema.field(id)?.ok_or(Error::InvalidCatalog)?;
        if field.kind != T::KIND {
            return Err(Error::InvalidField {
                id,
                reason: "stored schema kind differs from Rust type",
            });
        }
        if T::PRESERVE_MISSING && record.field(id)?.is_none() {
            return T::missing().map_err(|error| decode_error(id, error));
        }
        match schema.read_field(record, id)? {
            Some(value) => T::decode(&value).map_err(|error| decode_error(id, error)),
            None => T::missing().map_err(|error| decode_error(id, error)),
        }
    }
    pub fn set<T: FieldValue>(db: &Database, record: Record, id: u64, value: &T) -> Result<Record> {
        match value.encode_field(db)? {
            Some(value) => Ok(record.set(id, &value)?),
            None => Ok(record.remove(id)?),
        }
    }
    pub fn validate(record: &Record, schema: &Schema, type_id: u64) -> Result<()> {
        if record.type_id() != type_id || schema.type_id() != type_id {
            return Err(Error::TypeMismatch);
        }
        Ok(schema.validate(record)?)
    }
    pub fn unique<T: UniqueValue>() {}
}
