//! Generate raw bindings from the C header; fail closed on unsupported signatures.
use anyhow::{Context, Result, bail, ensure};
use regex::Regex;
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};
const BANNER: &str = "// Generated by cargo xtask odin-bindings. Do not edit declarations by hand.";
fn re(pattern: &str) -> Regex {
    Regex::new(pattern).expect("constant C ABI regex")
}
pub fn generate(header: &str) -> Result<String> {
    let text = re(r"(?s)/\*.*?\*/").replace_all(header, "");
    let handles = BTreeMap::from([
        ("wdb_database", "Database"),
        ("wdb_value", "Value"),
        ("wdb_snapshot", "Snapshot"),
        ("wdb_tx", "Transaction"),
        ("wdb_scan", "Scan"),
    ]);
    let mut lines = vec![
        BANNER.to_owned(),
        "// Ownership, synchronization, buffer, and native-path rules: packaged weekend_db.h."
            .into(),
        "package weekend_db".into(),
        "import \"core:c\"".into(),
        "".into(),
        "WEEKEND_DB_LIBRARY :: #config(WEEKEND_DB_LIBRARY, \"weekend_db\")".into(),
        "foreign import engine { WEEKEND_DB_LIBRARY }".into(),
        "".into(),
        "Status :: i32".into(),
    ];
    for name in ["Database", "Value", "Snapshot", "Transaction", "Scan"] {
        lines.push(format!("{name} :: distinct rawptr"));
    }
    lines.extend([
        "#assert(size_of(Database) == size_of(rawptr))".into(),
        "#assert(size_of(c.size_t) == size_of(uintptr))".into(),
        "".into(),
    ]);
    for regex in [
        re(r"\b(WDB_\w+)\s*=\s*(\d+)"),
        re(r"#define\s+(WDB_\w+)\s+(\d+)u"),
    ] {
        for m in regex.captures_iter(&text) {
            lines.push(format!("{} :: {}", &m[1], &m[2]));
        }
    }
    lines.extend(["".into(), "foreign engine {".into()]);
    let declarations = re(r"(?s)\b(wdb_status|uint32_t)\s+(wdb_\w+)\((.*?)\);");
    let declared: BTreeSet<_> = declarations
        .captures_iter(&text)
        .map(|c| c[2].to_owned())
        .collect();
    let all: BTreeSet<_> = re(r"\b(wdb_\w+)\s*\(")
        .captures_iter(&text)
        .map(|c| c[1].to_owned())
        .collect();
    ensure!(
        !declared.is_empty() && all == declared,
        "unsupported C ABI return/signature or no declarations"
    );
    let argument = re(r"^\s*(?:const\s+)?(\w+)\s*(\*\*|\*)?\s*(\w+)\s*$");
    for m in declarations.captures_iter(&text) {
        let mut params = vec![];
        if m[3].trim() != "void" {
            for param in m[3].split(',') {
                let p = argument
                    .captures(param)
                    .with_context(|| format!("unsupported C declaration: {param}"))?;
                let base = &p[1];
                let pointer = p.get(2).map(|m| m.as_str());
                let name = &p[3];
                let kind = if let Some(handle) = handles.get(base) {
                    match pointer {
                        Some("**") => format!("^{handle}"),
                        Some("*") => handle.to_string(),
                        _ => bail!("opaque handle must be a pointer"),
                    }
                } else {
                    let kind = match base {
                        "uint8_t" => "u8",
                        "uint64_t" => "u64",
                        "int32_t" => "i32",
                        "size_t" => "c.size_t",
                        _ => bail!("unsupported C parameter type: {base}"),
                    };
                    match pointer {
                        None => kind.to_owned(),
                        Some("*") => format!(
                            "{}{kind}",
                            if base == "uint8_t" || name == "buffer" {
                                "[^]"
                            } else {
                                "^"
                            }
                        ),
                        _ => bail!("unexpected pointer depth"),
                    }
                };
                params.push(format!(
                    "{}: {kind}",
                    if name == "map" { "map_value" } else { name }
                ));
            }
        }
        lines.push(format!(
            "    {} :: proc({}) -> {} ---",
            &m[2],
            params.join(", "),
            if &m[1] == "wdb_status" {
                "Status"
            } else {
                "u32"
            }
        ));
    }
    lines.push("}".into());
    lines.push("".into());
    Ok(lines.join("\n"))
}
pub fn check(root: &Path) -> Result<()> {
    ensure!(
        generate(&fs::read_to_string(root.join("include/weekend_db.h"))?)?
            == checkout_text(&fs::read_to_string(
                root.join("bindings/odin/weekend_db.odin")
            )?),
        "Odin binding differs from C header; run cargo xtask odin-bindings"
    );
    Ok(())
}
// Git may expand LF to CRLF on Windows. Normalize only that checkout transform;
// declaration text, trailing whitespace, bare CR and the final newline still matter.
fn checkout_text(text: &str) -> String {
    text.replace("\r\n", "\n")
}
pub fn run(root: &Path, check_only: bool) -> Result<()> {
    if check_only {
        check(root)
    } else {
        fs::write(
            root.join("bindings/odin/weekend_db.odin"),
            generate(&fs::read_to_string(root.join("include/weekend_db.h"))?)?,
        )?;
        Ok(())
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn checked_out_crlf_binding_passes_but_declaration_drift_rejects() {
        let dir = crate::support::Scratch::new(&std::env::temp_dir(), "odin-crlf").unwrap();
        fs::create_dir_all(dir.path().join("include")).unwrap();
        fs::create_dir_all(dir.path().join("bindings/odin")).unwrap();
        let header = include_str!("../../include/weekend_db.h");
        fs::write(
            dir.path().join("include/weekend_db.h"),
            header.replace("\r\n", "\n").replace('\n', "\r\n"),
        )
        .unwrap();
        let generated = generate(header).unwrap();
        let binding = dir.path().join("bindings/odin/weekend_db.odin");
        fs::write(&binding, generated.replace('\n', "\r\n")).unwrap();
        check(dir.path()).unwrap();
        fs::write(
            &binding,
            generated
                .replace("WDB_ABI_VERSION :: 1", "WDB_ABI_VERSION :: 2")
                .replace('\n', "\r\n"),
        )
        .unwrap();
        assert!(check(dir.path()).is_err());
        for changed in [
            generated.replace("Status :: i32", "Status :: i32 "),
            generated.trim_end_matches('\n').to_owned(),
            generated.replace("package weekend_db\n", "package weekend_db\r"),
        ] {
            fs::write(&binding, changed).unwrap();
            assert!(check(dir.path()).is_err());
        }
        run(dir.path(), false).unwrap();
        assert_eq!(fs::read_to_string(binding).unwrap(), generated);
    }
    #[test]
    fn generated_binding_preserves_every_header_signature_and_constant() {
        let header = include_str!("../../include/weekend_db.h");
        let original = checkout_text(include_str!("../../bindings/odin/weekend_db.odin"));
        assert_eq!(generate(header).unwrap(), original);
        assert_ne!(
            generate(&header.replace(
                "wdb_tx_commit(wdb_tx *tx, uint64_t *revision)",
                "wdb_tx_commit(wdb_tx *tx, int32_t *revision)"
            ))
            .unwrap(),
            original
        );
        assert_ne!(
            generate(&header.replace("WDB_ABI_VERSION 1u", "WDB_ABI_VERSION 2u")).unwrap(),
            original
        );
        assert!(generate(&format!("{header}\nuint64_t wdb_unknown(void);")).is_err());
    }
    #[test]
    fn unsupported_and_empty_declarations_reject() {
        for header in [
            "",
            "wdb_status wdb_bad(wdb_tx tx);",
            "wdb_status wdb_bad(uint64_t **revision);",
            "wdb_status wdb_bad(uint16_t n);",
            "wdb_status wdb_bad(int (*callback)(int));",
        ] {
            assert!(generate(header).is_err(), "{header}");
        }
    }
    #[test]
    fn map_keyword_and_bytes_output_pointer_rules() {
        let text = generate(
            "wdb_status wdb_get(const wdb_value *map, uint8_t *buffer, size_t *required);",
        )
        .unwrap();
        assert!(text.contains("map_value: Value, buffer: [^]u8, required: ^c.size_t"));
    }
}
